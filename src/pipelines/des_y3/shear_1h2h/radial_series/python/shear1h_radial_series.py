"""Miscentred one-halo shear via the radial_series strategy — Python.

The fast shear strategy of src/pipelines/des_y3/README.md
(`radial_series`): no redshift freeze, no per-sample profile
differentiation. Three steps per the approved design:

IMPORTANT LIMITATION: the offline profile is fixed at c = 4 for every mass
and redshift. There is no concentration--mass or concentration--redshift
evolution in U_ell. The exact redshift contraction below applies to the
population weights only; it does not restore a varying production c(M, z)
profile. Use direct radial evaluation rather than this table if that
concentration dependence is required.

  1. offline (once, committed): the unit-profile tables
     U_ell(ln x, ln x_mis), ell = 0..3, generated by
     generate_radial_series_tables.py under data/radial_series/;
  2. per sample: the exact redshift contraction
     W_ij(lnM) = int dz n dV/dOmega/dz Omega S_ij Sigma_crit_inv
     on fixed GL nodes (the SelGLCore convention), then the population
     moments of y = ln r_s(M): N_ij, ybar_ij, mu_2, mu_3;
  3. per (bin, R): interpolate U_0, U_2, U_3 at
     (ln R - ybar, ln r_mis - ybar), restore the analytic amplitude,
     and assemble

     O_ij(R) ~= N_ij A0(ybar) [ u_mix,0 + mu_2 u_mix,2 + mu_3 u_mix,3 ]

     with u_mix,ell = (1 - f_mis) U_ell^cen + f_mis Omega_m U_ell^mis
     (Omega_m is the miscentred component's rho_mult, exactly as
     NFW_DSIGMA_MIS::set_rho_mult).

The observable is the count-weighted stack N_ij[gamma_t^1h,full](R) on
the production (bin_index x r_perp) cartesian grid, bin slow / R fast —
the same grid semantics as Shear1hMisSel. The centred component is the
fixed-convention (c = 4, rho_crit) Wright & Brainerd profile — the
x_mis -> 0 limit of the same family as the miscentred term — NOT the
per-sample haloModel/dSigma_nfw table production uses; the known ~4%
shape difference between those two centred conventions is documented in
README.md and validations (see also validations/README.md and the
radial-factorization study §"two independently-sourced tables").

DataBlock contract
------------------
Reads (ini options):
    bin_index, r_perp             cartesian product grid (bin slow)
    zt_low, zt_high, lnm_low, lnm_high    required GL envelope
    n_lnm, n_z                    GL nodes (defaults 96, 64)
    lob_centers                   default 25 37.5 52.5 130
    ell_max                       2 or 3 (default 2: both the
                                  radial-factorization study and this
                                  implementation's validation find the
                                  mu_3 term does not improve the nearly
                                  symmetric DES Y3 mass weights; 3 is
                                  supported per the approved plan)
    table                         path to the U_ell npz (default
                                  data/radial_series/radial_series_nfw_mis_gamma_v1.npz)
Reads (datablock): the full Shear1hMisSel weight contract —
    sel_function/{lnM,z,S_stack}, mass_function/{m_h,z,dndlnmh},
    cluster_abundance/{hmf_s,hmf_q}, distances/{z,d_a},
    average_sigma_crit_inv/{zlense,sci_average},
    miscentering/{f_mis,tau_mis} (optional; defaults 0.22 / 0.17),
    cosmological_parameters/{h0,omega_m,omega_nu,omega_lambda,omega_k}
Writes:
    shear1h_radial_series/vals    (n_bins * n_r,)
    shear1h_radial_series/{norm,y_eff,mu2,mu3}   per-bin diagnostics

Status: reference/candidate implementation (validated against its own
exact fixed-GL mass integral; see README.md). Not a production entry
point; production remains Shear1hMisSel.so.
"""
