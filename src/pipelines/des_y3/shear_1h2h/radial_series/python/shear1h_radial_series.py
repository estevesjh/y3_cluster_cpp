def setup(options):
    from cosmosis.datablock import option_section
    sf = sel_kernels.load()
    cfg = {}
    cfg["bin_index"] = sf._read_array(options, option_section,
                                      "bin_index").astype(int)
    cfg["r_perp"] = sf._read_array(options, option_section, "r_perp")
    try:
        cfg["lob_centers"] = sf._read_array(options, option_section,
                                            "lob_centers")
    except Exception:
        cfg["lob_centers"] = np.asarray(dm.DEFAULT_LOB_CENTERS)
    for key in ("zt_low", "zt_high", "lnm_low", "lnm_high"):
        cfg[key] = float(options.get_double(option_section, key))
    for key, default in (("n_lnm", 96), ("n_z", 64), ("ell_max", 2)):
        try:
            cfg[key] = int(options.get_int(option_section, key))
        except Exception:
            cfg[key] = default
    if cfg["ell_max"] not in (2, 3):
        raise ValueError("shear1h_radial_series: ell_max must be 2 or 3")
    try:
        path = options.get_string(option_section, "table")
    except Exception:
        path = None
    cfg["table"] = RadialSeriesTable(path)   # loaded once, never per sample
    return cfg


def execute(block, cfg):
    t0 = time.perf_counter()
    source = dm.DataBlockSource(block)
    table = cfg["table"]

    weights = dm.MassZWeights(
        source, n_lnm=cfg["n_lnm"], n_z=cfg["n_z"],
        zt_lo=cfg["zt_low"], zt_hi=cfg["zt_high"],
        lnm_lo=cfg["lnm_low"], lnm_hi=cfg["lnm_high"], include_sci=True)
    norm, ybar, mu = weights.moments_of(pf.y_of_lnM, ell_max=3)

    f_mis = dm.read_mis_param(source, "f_mis", dm.F_MIS_DEFAULT)
    tau_mis = dm.read_mis_param(source, "tau_mis", dm.TAU_MIS_DEFAULT)
    omega_m = source.scalar("cosmological_parameters", "omega_m")
    lob = cfg["lob_centers"]

    vals = np.empty(cfg["bin_index"].size * cfg["r_perp"].size)
    n_r = cfg["r_perp"].size
    for i, b in enumerate(cfg["bin_index"]):
        r_mis = tau_mis * float(dm.R_lambda(lob[b % lob.size]))
        vals[i * n_r:(i + 1) * n_r] = evaluate_series(
            table, cfg["r_perp"], r_mis, norm[b], ybar[b], mu[b],
            f_mis=f_mis, rho_mult=omega_m, ell_max=cfg["ell_max"])

    block[OUTPUT_SECTION, "vals"] = vals
    block[OUTPUT_SECTION, "norm"] = norm
    block[OUTPUT_SECTION, "y_eff"] = ybar
    block[OUTPUT_SECTION, "mu2"] = mu[:, 2]
    block[OUTPUT_SECTION, "mu3"] = mu[:, 3]
    dt_ms = 1000.0 * (time.perf_counter() - t0)
    print(f"[shear1h_radial_series] {cfg['bin_index'].size} bins x "
          f"{n_r} radii, ell<={cfg['ell_max']} — {dt_ms:.0f} ms", flush=True)
    return 0


def cleanup(config):
    return 0
