#!/usr/bin/env python
"""External validation of the pipeline's linear P(k) input (issue #11 suite).

Compares the production ``matter_power_lin`` table (published by
``cp_camb.py``, the CosmoPower linear-P(k) emulator) against DIRECT CAMB
values at the same fiducial point -- an external reference, not a port
of the production code. The pinned values were generated by
``test/make_external_reference_pins.py`` from
``validations/second_halo_term/outputs/pk_camb.npz`` (itself produced by
``validations/second_halo_term/01_make_pk_camb.py``: CAMB at the
``mock_mcmc_widePlanck_values.ini`` fiducial on the production (k, z)
grid; k in h/Mpc, P in (Mpc/h)^3, comoving).

Tolerances are the emulator's measured intrinsic accuracy, NOT the
project 1e-3 default: emulator-vs-CAMB over the full 50x506 grid is
max 3.56e-3 / median 7.8e-4 (see pk_camb.npz dump_dev_*), and at the
pins below max 3.56e-3 / median 5.7e-4. Gates: max 5e-3, median 1.5e-3.
A failure here means the emulator (or its wiring) drifted from CAMB --
e.g. wrong weights file, wrong parameter mapping, or a unit change.

Skips (like the other dump-fed suites) when the fiducial dump is absent:
regenerate with  cosmosis cosmosis-models/real_pipeline_extract_prj2h.ini
(cp_camb paths point at pscratch; override them locally, see
BUILDING/building_macos docs).

Linear P(k) only, deliberately: the nonlinear input does not exist yet
(issue #9, accepted for now). pk_camb.npz already carries the Takahashi
halofit ``p_k_nl`` reference for the future nonlinear acceptance gate.
"""
from __future__ import annotations

import unittest
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
DUMP_DIR = REPO / "cosmosis-models" / "real_pipeline_extract_prj2h_output"
HAS_DUMP = (DUMP_DIR / "matter_power_lin").is_dir()
_SKIP_MSG = (f"requires a real-pipeline dump at {DUMP_DIR} -- run "
             "cosmosis cosmosis-models/real_pipeline_extract_prj2h.ini")

