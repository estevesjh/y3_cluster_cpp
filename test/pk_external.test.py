MAX_TOL = 5.0e-3     # emulator intrinsic, measured max 3.56e-3
MEDIAN_TOL = 1.5e-3  # measured median 5.7e-4 at the pins


@unittest.skipUnless(HAS_DUMP, _SKIP_MSG)
class TestLinearPkAgainstCamb(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        sec = DUMP_DIR / "matter_power_lin"
        cls.k = np.loadtxt(sec / "k_h.txt")
        cls.z = np.loadtxt(sec / "z.txt")
        cls.p = np.loadtxt(sec / "p_k.txt").reshape(cls.z.size, cls.k.size)

    def _pin_indices(self, grid, pins):
        idx = np.searchsorted(grid, pins)
        idx = np.clip(idx, 0, grid.size - 1)
        # accept the left neighbour when it is the closer grid point
        left = np.clip(idx - 1, 0, grid.size - 1)
        idx = np.where(np.abs(grid[left] - pins) < np.abs(grid[idx] - pins),
                       left, idx)
        np.testing.assert_allclose(grid[idx], pins, rtol=1e-9,
                                   err_msg="production grid moved; regenerate "
                                   "pins with make_external_reference_pins.py")
        return idx

    def test_fiducial_point_matches_reference_cosmology(self):
        vals = np.loadtxt(DUMP_DIR / "cosmological_parameters" / "values.txt",
                          dtype=str, delimiter="=", usecols=(0, 1))
        d = {k.strip(): v.strip() for k, v in vals}
        self.assertAlmostEqual(float(d["h0"]), 0.6766, places=4)
        self.assertAlmostEqual(float(d["omega_m"]), 0.311049, places=5)
        self.assertAlmostEqual(float(d["sigma8"]), 0.8238, places=4)

    def test_linear_pk_matches_direct_camb(self):
        zi = self._pin_indices(self.z, Z_PIN)
        ki = self._pin_indices(self.k, K_PIN)
        dev = np.abs(self.p[np.ix_(zi, ki)] / P_CAMB_PIN - 1.0)
        self.assertLessEqual(dev.max(), MAX_TOL,
                             f"max emulator-vs-CAMB dev {dev.max():.2e}")
        self.assertLessEqual(np.median(dev), MEDIAN_TOL,
                             f"median emulator-vs-CAMB dev {np.median(dev):.2e}")

    def test_growth_is_scale_independent_and_monotonic(self):
        # Linear P(k,z)/P(k,0) must be a scale-independent, decreasing D^2(z).
        zi = self._pin_indices(self.z, Z_PIN)
        ki = self._pin_indices(self.k, K_PIN)
        ratio = self.p[np.ix_(zi, ki)] / self.p[np.ix_([0], ki)]
        d2 = ratio.mean(axis=1)
        np.testing.assert_allclose(
            ratio, np.broadcast_to(d2[:, None], ratio.shape), rtol=2e-2)
        self.assertTrue(np.all(np.diff(d2) < 0.0))


if __name__ == "__main__":
    unittest.main(verbosity=2)
